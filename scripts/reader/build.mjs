/* Builds data/reader.json: everything the Reader can open, in published
 * order.
 *
 *   node scripts/reader/build.mjs          write data/reader.json
 *   node scripts/reader/build.mjs --check  exit 1 if the file is stale
 *
 * Sources:
 *   - Magazine issues: the article links on each MAGS/<MAG>/<issue>/ index,
 *     in the order the issue lists them (the editor's order), with each
 *     article's date and read time from its .mag-date line.
 *   - data/research.json posts (Research has no issues yet).
 *   - data/desks.json issues: a desk issue opens as a write-up built from
 *     its frozen edition data.
 *
 * Order: publications' editions by date, then the editor's order inside an
 * edition. An article with no date of its own keeps its place in the issue
 * rather than being given one. tests/reader.test.mjs runs --check.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const OUT = join(ROOT, 'data/reader.json');
const MAGAZINES = { START: 'START' };
const MONTHS = { jan: 1, feb: 2, mar: 3, apr: 4, may: 5, jun: 6, jul: 7, aug: 8, sep: 9, sept: 9, oct: 10, nov: 11, dec: 12 };

const ENTITIES = { amp: '&', nbsp: ' ', mdash: '—', ndash: '–', rsquo: '’', lsquo: '‘', ldquo: '“', rdquo: '”', middot: '·', ensp: ' ', quot: '"' };
const text = (html) => html.replace(/<[^>]+>/g, '').replace(/&(\w+);/g, (m, e) => ENTITIES[e] ?? m).replace(/\s+/g, ' ').trim();
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

/** "Sep 30, 2026" or "Sept 26, 2026" → "2026-09-30". */
export function isoDate(s) {
  const m = String(s).match(/\b([A-Z][a-z]{2,3})[a-z]*\.? (\d{1,2}), (\d{4})/);
  if (!m || !MONTHS[m[1].toLowerCase()]) return '';
  return `${m[3]}-${String(MONTHS[m[1].toLowerCase()]).padStart(2, '0')}-${m[2].padStart(2, '0')}`;
}

function magazineItems() {
  const out = [];
  for (const [dir, name] of Object.entries(MAGAZINES)) {
    const base = join(ROOT, 'MAGS', dir);
    for (const issue of readdirSync(base).sort()) {
      const index = join(base, issue, 'index.html');
      if (!statSync(join(base, issue)).isDirectory() || !existsSync(index)) continue;
      const html = readFileSync(index, 'utf8');
      const issueTitle = text(html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/)?.[1] ?? '');
      const hrefs = [...html.matchAll(/class="issue-list__title" href="([^"]+)"/g)].map((m) => m[1]);
      const edition = [];
      for (const rel of hrefs) {
        const file = join(base, issue, rel, 'index.html');
        if (!existsSync(file)) continue;
        const page = readFileSync(file, 'utf8');
        const meta = text(page.match(/<p class="mag-date">([\s\S]*?)<\/p>/)?.[1] ?? '');
        edition.push({
          id: `/MAGS/${dir}/${issue}/${rel}`,
          kind: 'article',
          publication: name,
          edition: issueTitle,
          title: text(page.match(/<h1[^>]*>([\s\S]*?)<\/h1>/)?.[1] ?? rel),
          dek: text(page.match(/<meta name="description" content="([^"]*)"/)?.[1] ?? ''),
          date: isoDate(meta),
          minutes: Number(meta.match(/~(\d+) min read/)?.[1]) || null
        });
      }
      const first = edition.map((i) => i.date).filter(Boolean).sort()[0] ?? '';
      out.push(...edition.map((i) => ({ ...i, edition_date: first })));
    }
  }
  return out;
}

function researchItems() {
  return JSON.parse(read('data/research.json')).posts.map((p) => ({
    id: p.href, kind: 'article', publication: 'Research', edition: '', title: p.title, dek: p.summary ?? '',
    date: p.date ?? '', minutes: null, edition_date: p.date ?? ''
  }));
}

function deskItems() {
  const out = [];
  for (const desk of JSON.parse(read('data/desks.json')).desks) {
    for (const issue of desk.issues ?? []) {
      out.push({
        id: issue.href, kind: 'desk-issue', publication: desk.name, edition: issue.title,
        title: `${desk.name}, ${issue.title}`, dek: desk.summary ?? '', date: issue.date ?? '',
        minutes: null, edition_date: issue.date ?? '', data: issue.data, desk: desk.id
      });
    }
  }
  return out;
}

export function build() {
  const all = [...magazineItems(), ...researchItems(), ...deskItems()];
  /* Stable: editions by date, then each edition's own order. */
  return all
    .map((item, n) => ({ item, n }))
    .sort((a, b) => a.item.edition_date.localeCompare(b.item.edition_date) || a.n - b.n)
    .map(({ item }) => { const { edition_date, ...rest } = item; return rest; });
}

const serialise = (items) => `${JSON.stringify({ _note: 'Generated by scripts/reader/build.mjs. Do not edit by hand.', items }, null, 2)}\n`;
export const isStale = () => !existsSync(OUT) || readFileSync(OUT, 'utf8') !== serialise(build());

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    if (isStale()) { console.error('data/reader.json is stale: run node scripts/reader/build.mjs'); process.exit(1); }
    console.log('data/reader.json is current');
  } else {
    const items = build();
    writeFileSync(OUT, serialise(items));
    console.log(`wrote ${items.length} items to data/reader.json`);
  }
}
